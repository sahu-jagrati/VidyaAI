def seed():
    db = SessionLocal()
    try:
        # Get existing Discount Sheet question IDs
        di_ids = [
            q.id for q in db.query(Question.id).filter(
                Question.subject_code == "quant",
                Question.topic == "Discount Sheet",
            ).all()
        ]

        # Delete attempts referencing those questions (FK constraint)
        if di_ids:
            attempts_deleted = (
                db.query(Attempt)
                .filter(Attempt.question_id.in_(di_ids))
                .delete(synchronize_session=False)
            )
            db.commit()
            print(f"✓ Deleted {attempts_deleted} attempt(s) for old Discount Sheet questions.")

        # Delete existing Discount Sheet questions
        deleted = (
            db.query(Question)
            .filter(
                Question.subject_code == "quant",
                Question.topic == "Discount Sheet",
            )
            .delete()
        )
        db.commit()
        print(f"✓ Deleted {deleted} old Discount Sheet questions.")

        for qdata in QUESTIONS:
            db.add(Question(**qdata))
        db.commit()
        print(f"✓ Inserted {len(QUESTIONS)} Discount Sheet questions.")
    except Exception as e:
        db.rollback()
        print(f"✗ Error: {e}")
        raise
    finally:
        db.close()


